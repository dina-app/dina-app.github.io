// Writes the support panel's per-app colour themes into assets/dinalab.css.
//
// The panel takes the colour of the app it is talking about: each seed below is
// the middle band of that app's three-band mark, and Google's Material colour
// utilities turn it into the few roles the panel uses, in light and dark. The
// general panel keeps the site's own Solar gold, so it has no entry here.
//
// This repo has no package.json, so the library comes from a path:
//   npm i --no-save --prefix /tmp/mcu @material/material-color-utilities@0.3.0
//   MCU=/tmp/mcu/node_modules/@material/material-color-utilities/index.js node scripts/build-support-themes.mjs
// Add --check to fail instead of writing when the stylesheet is out of date.
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

const SEEDS = {
  "salesforce-admin-toolkit": "#2540c8",
  "dinasheet-for-salesforce": "#009040",
  "sheetconnect-for-salesforce": "#006a60",
  "salesforce-agentic-bot": "#7040c5",
  "dina-dock-for-salesforce": "#087fc1",
  "dinadevops-for-salesforce": "#287675"
};

const START = "/* support app themes: generated by scripts/build-support-themes.mjs, do not edit */";
const END = "/* end support app themes */";

if (!process.env.MCU) {
  console.error("Set MCU to @material/material-color-utilities' index.js (see the comment at the top).");
  process.exit(2);
}
const { argbFromHex, hexFromArgb, Hct, TonalPalette } = await import(pathToFileURL(resolve(process.env.MCU)).href);

function roles(hex) {
  const seed = Hct.fromInt(argbFromHex(hex));
  const p = TonalPalette.fromHueAndChroma(seed.hue, Math.max(seed.chroma, 40));
  const soft = TonalPalette.fromHueAndChroma(seed.hue, Math.min(Math.max(seed.chroma, 40), 30));
  const quiet = TonalPalette.fromHueAndChroma(seed.hue, 18);
  const x = (palette, tone) => hexFromArgb(palette.tone(tone));
  return {
    light: {
      primary: x(p, 40), "on-primary": "#ffffff", "primary-container": x(soft, 92), "on-primary-container": x(soft, 25),
      secondary: x(p, 35), "secondary-container": x(quiet, 92), "on-secondary-container": x(quiet, 20),
      fill: x(p, 40), "on-fill": "#ffffff", "app-tint": x(quiet, 96), "app-bubble": x(quiet, 94)
    },
    dark: {
      primary: x(p, 80), "on-primary": x(p, 20), "primary-container": x(soft, 25), "on-primary-container": x(soft, 90),
      secondary: x(p, 78), "secondary-container": x(quiet, 25), "on-secondary-container": x(quiet, 90),
      fill: x(p, 80), "on-fill": x(p, 20), "app-tint": x(quiet, 15), "app-bubble": x(quiet, 20)
    }
  };
}

const block = vars => Object.entries(vars).map(([name, value]) => `  --${name}: ${value};`).join("\n");
let css = `${START}\n`;
for (const [slug, hex] of Object.entries(SEEDS)) {
  const { light, dark } = roles(hex);
  css += `dialog.support-panel[data-app="${slug}"] {\n${block(light)}\n}\n`;
  css += `:root[data-theme="dark"] dialog.support-panel[data-app="${slug}"] {\n${block(dark)}\n}\n`;
}
css += END;

const path = resolve(import.meta.dirname, "../assets/dinalab.css");
const sheet = readFileSync(path, "utf8");
const start = sheet.indexOf(START);
const end = sheet.indexOf(END);
const next = start >= 0 && end > start
  ? sheet.slice(0, start) + css + sheet.slice(end + END.length)
  : `${sheet.trimEnd()}\n\n${css}\n`;

if (process.argv.includes("--check")) {
  if (next !== sheet) { console.error("assets/dinalab.css support themes are stale: run scripts/build-support-themes.mjs"); process.exit(1); }
  console.log("support themes are current");
} else {
  writeFileSync(path, next);
  console.log(`Wrote ${Object.keys(SEEDS).length} app themes into assets/dinalab.css`);
}
